#!/usr/bin/env bash

# The proxy's filter, combined from allow-lists; sourced by `agent-sandbox`

# Combines the allow-lists that exist into the filter file; succeeds only if its
# content changed, in which case the proxy has to be recreated to pick it up
update_filter() {
    local filter="$1" tmp source
    shift
    mkdir -p "$(dirname "$filter")"
    tmp="$(mktemp "$filter.XXXXXX")"
    {
        echo "# Generated by agent-sandbox; edit the allow-lists instead"
        for source in "$@"; do
            if [[ -f "$source" ]]; then
                cat "$source"
                echo
            fi
        done
    } > "$tmp"
    if cmp -s "$tmp" "$filter"; then
        rm "$tmp"
        return 1
    fi
    mv "$tmp" "$filter"
}

# Prints the hosts in the filter file as a Markdown list in a readable form,
# _e.g._ `^.*\.example\.com$` becomes `*.example.com`
filter_hosts() {
    # shellcheck disable=SC2016
    sed -e 's/#.*//' -e '/^[[:space:]]*$/d' -e 's/^\^//' -e 's/\$$//' \
        -e 's/\\\././g' -e 's/\.\*/*/g' -e 's/.*/- `&`/' "$1"
}
